// Inlines Leaflet into a TS module so the shift-location WebView map works
// without a CDN. Re-run after upgrading the `leaflet` package:
//   node scripts/generate-leaflet-source.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const dist = join(dirname(require.resolve('leaflet/package.json')), 'dist');
const { version } = require('leaflet/package.json');
const js = readFileSync(join(dist, 'leaflet.js'), 'utf8');
const css = readFileSync(join(dist, 'leaflet.css'), 'utf8');

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const out = join(root, 'src/assets/leaflet/leafletSource.ts');
writeFileSync(
  out,
  `/* eslint-disable */\n// Generated by scripts/generate-leaflet-source.mjs from leaflet@${version}. Do not edit.\n` +
    `export const LEAFLET_JS = ${JSON.stringify(js)};\n` +
    `export const LEAFLET_CSS = ${JSON.stringify(css)};\n`,
);
console.log(`Wrote ${out}`);
